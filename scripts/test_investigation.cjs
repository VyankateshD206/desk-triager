// Labeled observable-record fixtures. They are never injected into the live UI.
const assert=require('node:assert/strict'), fs=require('node:fs'), vm=require('node:vm');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync('triager/static/investigation.js','utf8'),sandbox);
const view=sandbox.window.DeskInvestigation;
assert.equal(view.shortRunId('12345678-1234-5678-9012-123456789abc'),'12345678…9abc');
assert.equal(view.shortRunId('short-id'),'short-id');
assert.equal(view.shortRunId(null),'');
assert.equal(view.configuredProvider('openai'),'OpenAI');
assert.equal(view.configuredProvider('gemini'),'Gemini');
assert.match(view.configuredProvider('offline'),/no LLM/);
assert.equal(view.configuredProvider(null),'Unknown');
assert.match(view.activeFaults(null),/Connect/);
assert.match(view.activeFaults({mode:'external'}),/External telemetry/);
assert.match(view.activeFaults({mode:'simulated desk',faults:{}}),/No active.*Retained incidents/);
assert.match(view.activeFaults({mode:'simulated desk',faults:{'market-feed':'tick_gap'}}),/market-feed: tick gap/);
const offline={provider:'offline',node_trace:[{node:'collect_context',latency_ms:0},{node:'reason',latency_ms:1},{node:'verify',latency_ms:2},{node:'critic',latency_ms:.1},{node:'final_report',latency_ms:1}],model_calls:[],verification:{checks:'citations_quotes_numeric_values',issues:[],semantic_support:'not_assessed'}};
assert.equal(view.trace({diagnosis:{}}).length,0);
assert.equal(view.trace(offline).length,5);
assert.equal(view.trace(offline)[1].name,'Offline rule analysis');
assert.equal(view.trace(offline)[3].name,'Critic gate');
assert.equal(view.trace(offline)[3].status,'No assessment recorded');
assert.match(view.providerLabel(offline),/rule-based/);
assert.equal(view.duration(null),'Duration not recorded');
assert.equal(view.duration(0),'0 ms');
const model={...offline,provider:'gemini',node_trace:[{node:'reason',latency_ms:42},{node:'tools',latency_ms:10},{node:'reason',latency_ms:32}],model_calls:[{provider:'gemini'}]};
assert.equal(view.trace(model).length,3);
assert.equal(view.trace(model)[0].name,'Agent reasoning');
assert.equal(view.trace(model)[2].name,'Agent reasoning');
assert.match(view.providerLabel(model),/Gemini/);
assert.equal(view.trace({...model,provider:'offline',fallback_reason:'UnsupportedQuote'})[0].name,'Agent reasoning');
assert.equal(view.trace({...offline,verification:{semantic_support:'model_critic_assessed'}})[3].name,'Model critic');
assert.equal(view.trace({...offline,verification:{semantic_support:'critic_unavailable'}})[3].status,'Unavailable');
assert.match(view.trace({...offline,verification:{}})[2].explanation,/not recorded/);
const collected={source:'telemetry:1',evidence_id:'log-1',content:'Runbook: this is ordinary logged text'};
assert.equal(view.evidenceType(collected).kind,'collected');
assert.equal(view.evidenceType({source:'tool:get_metrics',content:'[]'}).kind,'collected');
const retrieved={source:'tool:search_runbooks',evidence_id:'rag-1',content:JSON.stringify([{document_id:'doc1',content:'Reviewed runbook excerpt',version:'1',source:'runbook:gateway',score:.7}])};
assert.equal(view.evidenceType(retrieved).documents.length,1);
assert.match(view.evidenceType(retrieved).label,/Knowledge retrieval/);
assert.match(view.evidenceType({...retrieved,content:'[]'}).label,/no document/);
assert.match(view.evidenceType({...retrieved,content:'invalid json'}).label,/unrecognized/);
assert.equal(view.evidenceType({source:'unknown',content:retrieved.content}).kind,'other');
assert.equal(view.relatedFindings(collected,{diagnosis:{hypotheses:[{cause:'Observed error',evidence_ids:['log-1']},{cause:'Other',evidence_ids:['rag-1']}]}}).length,1);
assert.equal(view.relatedFindings(collected,{diagnosis:{hypotheses:[]}}).length,0);
assert.match(view.toolSource({tool:'query_logs',status:'blocked'}),/not confirmed/);
assert.match(view.toolSource({tool:'search_runbooks',status:'ok'}),/retrieval/);
const safe=view.usage({provider:'gemini',model:'fixture',input_tokens:20,output_tokens:5,latency_ms:3,reasoning:'DO_NOT_RENDER_PRIVATE_CONTENT',messages:['DO_NOT_RENDER_PRIVATE_CONTENT'],parts:[{thought:true,text:'DO_NOT_RENDER_PRIVATE_CONTENT'}]});
assert.doesNotMatch(JSON.stringify(safe),/DO_NOT_RENDER_PRIVATE_CONTENT/);
assert.equal(safe.input_tokens,20);
assert.doesNotMatch(JSON.stringify(view.trace({...offline,node_trace:[{node:'reason',latency_ms:1,messages:['DO_NOT_RENDER_PRIVATE_CONTENT']}]})),/DO_NOT_RENDER_PRIVATE_CONTENT/);
console.log('Investigation checks passed: observed nodes, offline/model/fallback, critic gates, missing timings, evidence provenance, retrieval, tool failures and usage allowlist.');

for (const path of process.argv.slice(2)) {
  const record=JSON.parse(fs.readFileSync(path,'utf8'));
  assert.equal(view.trace(record).length,(record.node_trace || []).length);
  for (const item of record.evidence_items || []) assert.ok(['collected','retrieval','other'].includes(view.evidenceType(item).kind));
  if (record.provider==='offline') assert.match(view.providerLabel(record),/rule-based/);
  else if (record.provider==='gemini') assert.match(view.providerLabel(record),/Gemini/);
  console.log('Recorded run checked:',record.provider,view.trace(record).length,'nodes,',(record.model_calls || []).length,'model calls');
}
